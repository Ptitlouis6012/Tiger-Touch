"""Turn tools/brand_logos.json into main/ui/brand_logos.c.

    python tools/make_brand_logos.py

brand_logos.json holds, per brand, a 32x32 alpha mask (base64, 1 byte per pixel)
made from Tiger Studio Manager's own logos
(TigerTag-Studio-Manager/assets/svg/icons/logo_*.svg): each SVG rasterised at
256 px, trimmed to its drawn area and fitted into 32x32 with a 2 px margin.
The device paints the mask in one colour, the way Studio does with its icon
masks, so every brand reads the same on the dark card.

Klipper and OctoPrint are Studio plugins: their logos are
renderer/printers/<plugin>/img/logo.svg, made the same way.

Prusa's source is a placeholder "P" in Studio, not the real artwork: replace it
there first, then regenerate.
"""
import base64
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "brand_logos.json"
OUT = ROOT / "main" / "ui" / "brand_logos.c"
BRANDS = ["bambulab", "creality", "anycubic", "elegoo", "flashforge", "prusa", "snapmaker", "klipper", "octoprint"]
SZ = 32


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    lines = [
        "/* Generated by tools/make_brand_logos.py from tools/brand_logos.json: do not edit.",
        " * 32x32 alpha masks of the brands' logos, painted in one colour by the screens. */",
        "",
        '#include "brand_logos.h"',
        "",
        "#include <string.h>",
        "",
    ]
    for b in BRANDS:
        raw = base64.b64decode(data[b])
        assert len(raw) == SZ * SZ, b
        lines.append(f"static const uint8_t MAP_{b.upper()}[] = {{")
        for i in range(0, len(raw), 32):
            lines.append("    " + ",".join(f"0x{v:02x}" for v in raw[i:i + 32]) + ",")
        lines.append("};")
        lines.append(f"static const lv_image_dsc_t LOGO_{b.upper()} = {{")
        lines.append("    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, "
                     f".w = {SZ}, .h = {SZ}, .stride = {SZ}}},")
        lines.append(f"    .data_size = sizeof MAP_{b.upper()},")
        lines.append(f"    .data = MAP_{b.upper()},")
        lines.append("};")
        lines.append("")
    lines.append("const lv_image_dsc_t *brand_logo(const char *brand)")
    lines.append("{")
    lines.append("    static const struct")
    lines.append("    {")
    lines.append("        const char *id;")
    lines.append("        const lv_image_dsc_t *img;")
    lines.append("    } MAP[] = {")
    for b in BRANDS:
        lines.append(f'        {{"{b}", &LOGO_{b.upper()}}},')
    lines.append("    };")
    lines.append("    for (size_t i = 0; brand && i < sizeof MAP / sizeof MAP[0]; i++)")
    lines.append("    {")
    lines.append("        if (strcmp(MAP[i].id, brand) == 0)")
    lines.append("        {")
    lines.append("            return MAP[i].img;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(BRANDS)} logos)")


if __name__ == "__main__":
    main()

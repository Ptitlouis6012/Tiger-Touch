"""Turn tools/pictos.json into main/ui/pictos.c.

    python tools/make_pictos.py

pictos.json holds, per pictogram and size, a square alpha mask (base64, 1 byte
per pixel, cut into 16-character pieces so that no line is a long run a secret
scanner would flag). The sources are the SVGs in tools/pictos/: nozzle, bed and chamber
are Tiger Studio Manager's own (assets/svg/icons/icon_*.svg, the pictograms of
its printer cards), clock is Studio's, file, flag and bulb are drawn in the same
style (stroke 2 on a 24 grid, round ends) because Studio has none.

Each SVG is drawn at the mask's size with its viewBox fitted whole and
centred, so the icons keep their relative sizes as in Studio, and the alpha
channel is kept. This was done in a browser (canvas, drawImage of the SVG at
the target size): there is no rasteriser in the build. The device paints a
mask in one colour (lv_obj_set_style_image_recolor), like the brand logos.

Sizes: 24 for the temperature tiles (the cards, the full view) and the light
button, 16 for the labels (file, time left, estimated end).
"""
import base64
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "pictos.json"
OUT = ROOT / "main" / "ui" / "pictos.c"
ORDER = ["nozzle", "bed", "chamber", "file", "clock", "flag", "bulb"]


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    masks = []  # (name, size, raw)
    for key in sorted(data, key=lambda k: (ORDER.index(re.sub(r"\d+$", "", k)), int(re.search(r"\d+$", k).group()))):
        name = re.sub(r"\d+$", "", key)
        size = int(re.search(r"\d+$", key).group())
        raw = base64.b64decode("".join(data[key]))
        assert len(raw) == size * size, key
        masks.append((name, size, raw))

    lines = [
        "/* Generated by tools/make_pictos.py from tools/pictos.json: do not edit.",
        " * Square alpha masks of the pictograms, painted in one colour by the screens. */",
        "",
        '#include "pictos.h"',
        "",
    ]
    for name, size, raw in masks:
        ident = f"{name.upper()}_{size}"
        lines.append(f"static const uint8_t MAP_{ident}[] = {{")
        for i in range(0, len(raw), size):
            lines.append("    " + ",".join(f"0x{v:02x}" for v in raw[i:i + size]) + ",")
        lines.append("};")
        lines.append(f"static const lv_image_dsc_t IMG_{ident} = {{")
        lines.append("    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, "
                     f".w = {size}, .h = {size}, .stride = {size}}},")
        lines.append(f"    .data_size = sizeof MAP_{ident},")
        lines.append(f"    .data = MAP_{ident},")
        lines.append("};")
        lines.append("")
    lines.append("const lv_image_dsc_t *picto(picto_t id, int size)")
    lines.append("{")
    lines.append("    static const struct")
    lines.append("    {")
    lines.append("        picto_t id;")
    lines.append("        int size;")
    lines.append("        const lv_image_dsc_t *img;")
    lines.append("    } MAP[] = {")
    for name, size, _ in masks:
        lines.append(f"        {{PICTO_{name.upper()}, {size}, &IMG_{name.upper()}_{size}}},")
    lines.append("    };")
    lines.append("    for (size_t i = 0; i < sizeof MAP / sizeof MAP[0]; i++)")
    lines.append("    {")
    lines.append("        if (MAP[i].id == id && MAP[i].size == size)")
    lines.append("        {")
    lines.append("            return MAP[i].img;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    lines.append("")
    lines.append("lv_obj_t *picto_create(lv_obj_t *parent, picto_t id, int size, lv_color_t color)")
    lines.append("{")
    lines.append("    lv_obj_t *im = lv_image_create(parent);")
    lines.append("    lv_image_set_src(im, picto(id, size));")
    lines.append("    lv_obj_set_style_image_recolor(im, color, 0);")
    lines.append("    lv_obj_set_style_image_recolor_opa(im, LV_OPA_COVER, 0);")
    lines.append("    lv_obj_set_clickable(im, false);")
    lines.append("    return im;")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(masks)} masks)")


if __name__ == "__main__":
    main()
